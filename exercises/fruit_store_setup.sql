/*
This SQL script sets up a simple database schema for a fruit store, including a table for fruit
data and a separate table for vector embeddings that will be generated using the Mistral API.

This should be run inside the database fruit_store, which is created in the master_setup.sql script. 
The master_setup.sql script also sets the MISTRAL_API_KEY environment variable, 
which is required for generating the embeddings using the Mistral API.

Embedding generation is not done in this script, but rather in the fruit_store_chat.sql script,
 which contains the necessary functions and triggers to generate and store the embeddings 
 whenever new fruit data is inserted or updated.

 This is part of the DLH Training Class for AI and Postgres, and is meant for educational purposes to 
 demonstrate how to set up a database schema for vector embeddings and how to integrate with an 
 external API for generating those embeddings.

 Last Update: 2026-04-30
*/


-- Add the vector extension, which is required for storing vector embeddings in Postgres
CREATE EXTENSION IF NOT EXISTS vector;
-- Add the PL/Python extension, which is required for creating stored procedures and functions in Python, which we will use to call the Mistral API to generate embeddings
CREATE EXTENSION IF NOT EXISTS plpython3u;

-- Define a simple table to hold fruit data without vector embeddings, 
-- Store embeddings in a separate table

DROP TABLE IF EXISTS fruit;

CREATE TABLE fruit (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name TEXT NOT NULL,
  description TEXT
);

-- Insert sample fruit data with 3-dimensional feature vectors
INSERT INTO fruit (name, description) VALUES
  ('Apple',  'Sweet, medium red, medium firm'),
  ('Banana', 'Very sweet, yellow, soft'),
  ('Mango',  'Very sweet, orange, very soft'),
  ('Lemon',  'Very tart, yellow, firm'),
  ('Orange', 'Sweet-tart, orange, firm'),
  ('Peach',  'Sweet, pinkish, very soft'),
  ('Grape',  'Sweet, purple/green, soft-ish'),
  ('Kiwi',   'Tart-sweet, brown/green, soft'),
  ('Potato', 'Starchy, brown, firm'),
  ('Cherry', 'Sweet, red, firm');

-- now we will create a table to hold the embeddings, which will be generated using the Mistral API and stored as 1024-dimensional vectors
CREATE TABLE embedding (
    fruit_id INTEGER PRIMARY KEY,
    embedding_vector vector(1024),
    FOREIGN KEY (fruit_id) REFERENCES fruit(id)
);