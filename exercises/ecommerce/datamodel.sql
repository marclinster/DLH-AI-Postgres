-- uper simple CTE

WITH massachusetts_customers AS (
    SELECT id, first_name, last_name, city, postal_code
    FROM customer
    WHERE postal_code ILIKE 'MA%'
)
SELECT city, last_name, first_name
FROM massachusetts_customers
ORDER BY city ASC, last_name ASC, first_name ASC;

-- CTE that shows what the top 10 customers bought in the last 6 months, by quantity sold, with product details

WITH top_customers AS (
    -- this gets me the top 10 customers
	SELECT customer_id, first_name, last_name, SUM(qty*price) AS total_spent
	FROM sales_transaction_full_details
	GROUP BY customer_id, first_name, last_name
	ORDER BY total_spent DESC
	LIMIT 10
)
-- look at all the sales transactions for those customers and 
-- sum up the quantity sold by product, with product details
SELECT 
	stfd.product_id, stfd.product_label, SUM(stfd.qty) AS total_qty_sold
FROM sales_transaction_full_details stfd
JOIN top_customers tc ON tc.customer_id = stfd.customer_id
GROUP BY stfd.product_id, stfd.product_label
ORDER BY total_qty_sold DESC;


