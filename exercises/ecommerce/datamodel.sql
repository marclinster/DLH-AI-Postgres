\echo '--> Creating product tables...'

CREATE TABLE product.category (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    label VARCHAR(50) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE product.brand (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    label VARCHAR(50) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE product.country_of_origin (
    brand_id INTEGER PRIMARY KEY REFERENCES product.brand (id),
    --- three digit ISO 3166-1 A-3
    alpha3_code VARCHAR(3) NOT NULL,
    name TEXT
);

CREATE TABLE product.product (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    category_id INTEGER NOT NULL REFERENCES product.category (id),
    brand_id INTEGER NOT NULL REFERENCES product.brand (id),
    label VARCHAR (50) NOT NULL,
    shortdescription VARCHAR(200) NOT NULL,
    longdescription TEXT,
    image_filename VARCHAR(50)
);

CREATE TABLE product.product_variant (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    product_id INTEGER NOT NULL REFERENCES product.product(id) ON DELETE CASCADE,
    attributes JSONB,
    price NUMERIC(10, 2) NOT NULL CHECK (price >= 0)
);

\echo '--> Defining customer tables...'            

CREATE TABLE customer.customer (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    phone_numbers JSONB,
    street_address VARCHAR(100) NOT NULL,
    city VARCHAR(100) NOT NULL,
    postal_code VARCHAR(20) NOT NULL,
    country VARCHAR(50) NOT NULL
);


\echo '--> Creating sales tables...'

CREATE TABLE sales.sales_transaction (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    transaction_date DATE NOT NULL DEFAULT CURRENT_DATE,
    customer_id INTEGER NOT NULL REFERENCES customer(id)
);
-- Sales transaction line items

CREATE TABLE sales.sales_transaction_line (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    sales_transaction_id INTEGER NOT NULL REFERENCES sales.sales_transaction(id) ON DELETE CASCADE,
    product_variant_id INTEGER NOT NULL REFERENCES product.product_variant(id),
    qty INTEGER NOT NULL CHECK (qty > 0),
    price NUMERIC(10, 2) NOT NULL CHECK (price >= 0)
);

\echo '--> a view that aligns product, product variant, brand, country of origin and category for easier reporting'


CREATE VIEW product.product_full_details AS
SELECT
	pv.id AS product_variant_id,
	p.id AS product_id,
	p.label AS product_label,
	p.shortdescription AS product_shortdescription,
	p.longdescription AS product_longdescription,
	br.label AS brand_label,
	br.description AS brand_description,
	coo.name AS country_of_origin,
	c.label AS category_label,
	pv.attributes AS product_variant_attributes,
	pv.price AS product_variant_price
FROM product_variant pv
JOIN product p ON pv.product_id = p.id
JOIN category c ON p.category_id = c.id
JOIN brand br ON p.brand_id = br.id
JOIN country_of_origin coo ON coo.brand_id = br.id;


\echo '--> a view that aligns sales transactions with product details and customer details for easier reporting'

CREATE OR REPLACE VIEW sales.sales_transaction_full_details AS
SELECT 
	st.id, st.transaction_date,
 	stl.qty, stl.price,
	pfd.product_id, pfd.product_label, pfd.product_shortdescription, pfd.product_longdescription, pfd.brand_label, 
	pfd.brand_description, pfd.country_of_origin, pfd.category_label, pfd.product_variant_attributes, pfd.product_variant_price,
	c.id AS customer_id, c.first_name, c.last_name, c.city, c.postal_code, c.country
FROM sales_transaction st
JOIN sales_transaction_line stl ON stl.sales_transaction_id = st.id
JOIN product_full_details pfd ON pfd.product_variant_id = stl.product_variant_id
JOIN customer c ON c.id = st.customer_id;

