Last updated Nov 2, 2026

****************************************************************************************************/





DROP TABLE IF EXISTS customer CASCADE;

CREATE TABLE customer  (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    first_name TEXT,
    last_name TEXT,
    since DATE,
    phone_numbers JSONB
);    

