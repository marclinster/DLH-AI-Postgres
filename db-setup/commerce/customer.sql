CREATE OR REPLACE PROCEDURE assign_random_phone_numbers_to_customers()
LANGUAGE plpgsql
AS $$
DECLARE
    v_customer_id INT;
    v_phone_number TEXT;
    v_phone_group TEXT;
    v_phone_label TEXT;
    v_phone_json_work JSONB;
    v_phone_json_private JSONB;
    v_phone_json JSONB;
    v_country_code TEXT[];
    
BEGIN
    -- Clear existing phone numbers
    UPDATE customer SET phone_numbers = NULL;
    -- initialize the country codes array
    v_country_code := ARRAY['(+352)', '(+49)', '(+33)', '(+44)', '(+1)'];

    FOR v_customer_id IN SELECT id FROM customer LOOP
        -- Generate random phone numbers for work and private

        -- generate work phone numbers (between 0 and 2 random numbers for each customer)
        v_phone_json_work := jsonb_build_array();
        FOR i IN 0..(random() * 2)::INT LOOP
            -- Generate a random phone number with a random country code and append it to the work phone numbers JSONB array
            v_phone_json_work := v_phone_json_work ||
            jsonb_build_object(
                'country_code', v_country_code[1 + floor(random() * array_length(v_country_code, 1))], 
                'number', to_char(floor(random() * 1000000000)::INT, 'FM000"."000"."000'));
        END LOOP;
        
        v_phone_json_private := jsonb_build_array();
        FOR i IN 0..(random() * 2)::INT LOOP
            -- Generate a random phone number with a random country code and append it to the private phone numbers JSONB array
            v_phone_json_private := v_phone_json_private ||
            jsonb_build_object(
                'country_code', v_country_code[1 + floor(random() * array_length(v_country_code, 1))], 
                'number', to_char(floor(random() * 1000000000)::INT, 'FM000"."000"."000'));
        END LOOP;
        -- Combine work and private phone numbers into a single JSONB object
        v_phone_json := jsonb_build_object(
            'work', v_phone_json_work,
            'private', v_phone_json_private
        );
        
        -- Update the customer record with the generated phone numbers
        UPDATE customer SET phone_numbers = v_phone_json WHERE id = v_customer_id;
    END LOOP;
END;
$$; 

CALL assign_random_phone_numbers_to_customers();


